-- page_views に「内部からの閲覧か」の印を足す。
--
-- ## なぜ要るか
--
-- 利用者の指摘「私だけしか見ていないのにビューが増える」。実際そのとおりで、
-- /api/metrics/view は UA でボットを弾くだけで、**運営者を除外する仕組みが
-- 無い。**ログイン中でも管理者でも 1 件記録される。
--
-- さらに PageViewBeacon は usePathname の変化で発火するので、サイト内を
-- 10 ページ見れば 10 PV。開発中のリロードもそのまま数に乗る。
--
-- つまり今の数字は「新規流入」ではなく「自分を含む全アクセス」。
--
-- ## 落とすのではなく印を付ける
--
-- 記録そのものを止める案もあるが、**捨てると後から考え直せない。**
-- 「内部を除いた数」と「全部の数」を両方出せるほうが強い。列を 1 つ
-- 足して、集計側で分ける。
--
-- 印を付ける経路は 2 つ。
--
--   サーバ側  ログインしているのが ADMIN_EMAIL なら internal
--   端末側    その端末で「計測から除外」を選んでいれば internal
--
-- 2 つあるのは、片方では漏れるため。ログアウトして見れば 1 つめは
-- 効かないし、別の端末を使えば 2 つめは効かない。
--
-- ## 既定値を置かない
--
-- **NULL は「この列ができる前の行」。**内部か外部かが分からない、という
-- 事実をそのまま残す。
--
-- ここで DEFAULT false を置くと、**当てた日より前の全行が「外部からの
-- 閲覧だった」と主張することになる。**実際にはその中に運営者の閲覧が
-- 相当数含まれている（それがこの列を足す理由そのもの）。集計側で
-- 「不明」として分けられるよう、NULL のままにする。
--
-- 新しい行は必ず true / false のどちらかを明示して入れる。
--
-- 足すだけの DDL。二度当てても同じ結果になる。
-- 定義は prisma/schema.prisma の PageView と揃えること。
--
-- 適用: Actions → Apply additive SQL → file: このファイル名 / mode: apply

ALTER TABLE "page_views"
  ADD COLUMN IF NOT EXISTS "is_internal" BOOLEAN;

-- 既定の集計は「内部を除いた日別 PV/UV」。日で絞ってから内部を外すので、
-- 既存の (day, path) とは別に (day, is_internal) を持つ。
CREATE INDEX IF NOT EXISTS "page_views_day_internal_idx"
ON "page_views" ("day", "is_internal");
