-- 登録した地点に「その物件のページ」への印を持たせる（2026-09-15）
--
-- ## なぜ
--
-- 利用者の依頼。物件のページ（SUUMO・HOME'S・シャーメゾン・いい部屋ネット
-- など）を見ながら「この部屋の方位は？」を確かめたい。
--
-- **URL の中身は取りに行かない。**取りに行けばスクレイピングで、nifty の
-- 特約は「プログラム等を用いて自動的にデータを収集する行為」を名指しで
-- 禁じている。利用者が 1 件ずつ押すのだとしても、取りに行くのはこちらの
-- プログラムなので、量は違っても規約上の扱いは変わらない
-- （CLAUDE.md 3 節・backlog 25 節で一度間違えた形）。
--
-- だから**印として持つだけ**にする。場所は利用者が地図か地名で指し、
-- 方位・段階・距離・相場・公的統計はその座標に対して走る。URL は
-- 「どの物件の話だったか」を後で思い出すための控え。
--
-- ## 足すだけ
--
-- `ADD COLUMN IF NOT EXISTS` の 2 列だけ。**既定値（DEFAULT）を置かない。**
-- 置くと当てた日に既存の全行がその値を持ったことになる（CLAUDE.md 6 節）。
-- どちらも NULL 可で、入れていない地点は今までどおり。
--
-- ## 入るのは個人情報
--
-- 「どの物件を見ているか」は住まいの計画そのもの。`user_spots` は既に
-- 名前と座標を持っていて、API は本人の行しか触らない・ログに出さない・
-- キャッシュに載せない、を検査で固定してある（`__tests__/spotsRoute.test.ts`）。
-- 新しい 2 列も同じ守りの内側に置く。
--
--   url  … https のみ。画面で開くだけで、サーバーからは取りに行かない
--   memo … 利用者の覚え書き（間取り・家賃など。手で書く）

ALTER TABLE user_spots ADD COLUMN IF NOT EXISTS url text;
ALTER TABLE user_spots ADD COLUMN IF NOT EXISTS memo text;
