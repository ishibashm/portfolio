/**
 * 入力が URL かどうか。**綴りだけを見る。開きに行かない。**
 *
 * 地名の欄から外部の住所サービスへ文字列を渡す口が 2 つある。
 *
 *   - `/api/geocode`         … 読み取れない入力を nominatim へ載せる
 *   - `/api/geocode/suggest` … 打っている途中の文字列を国土地理院へ載せる
 *
 * どちらも `q` をそのまま載せるので、物件ページの URL を貼られると
 * **貼った本人が見ている物件が外部のサービスに渡る。**地点に物件の URL を
 * 控える欄（#1310）と、URL を貼って街を決める導線（#1312）がある以上、
 * 地名の欄に URL が貼られるのは想定内の操作。
 *
 * 前者は #1312 で折り返したが、後者は残っていた（2026-09-24。地名の欄は
 * 打ち止めから 400ms で候補を引くので、**貼っただけで**外へ出ていた）。
 * 同じ規則を 2 か所に書かないよう、ここに 1 つだけ置く（CLAUDE.md 3 節
 * 「約束の範囲は入口の集合で決まる」）。
 */
export function looksLikeUrl(raw: string): boolean {
  return (
    /^(?:https?:)?\/\//i.test(raw.trim()) ||
    /^[a-z][a-z0-9+.-]*:/i.test(raw.trim())
  );
}
