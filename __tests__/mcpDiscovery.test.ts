// @vitest-environment node
import { describe, expect, it, vi } from "vitest";
import { GET } from "@/app/.well-known/oauth-protected-resource/api/mcp/personal/route";
import {
  createMcpDiscoveryContract,
  MCP_AS_METADATA_URL,
  MCP_AUTHORIZATION_ISSUER,
  MCP_RESOURCE_METADATA_URL,
} from "@/lib/mcpDiscovery";
import { MCP_PERSONAL_RESOURCE } from "@/lib/mcpAuthorizationConfig";

vi.mock("@/lib/prisma", () => {
  throw new Error("discovery must not access DB");
});
vi.mock("@/lib/userConfig", () => {
  throw new Error("discovery must not use login cookies");
});
const metadata = () => ({
  issuer: MCP_AUTHORIZATION_ISSUER,
  authorization_endpoint: `${MCP_AUTHORIZATION_ISSUER}/auth`,
  token_endpoint: `${MCP_AUTHORIZATION_ISSUER}/token`,
  revocation_endpoint: `${MCP_AUTHORIZATION_ISSUER}/token/revocation`,
  scopes_supported: ["read:profiles"],
  response_types_supported: ["code"],
  code_challenge_methods_supported: ["S256"],
  grant_types_supported: ["authorization_code", "refresh_token"],
});

describe("MCP discovery deployment gate and contract", () => {
  it.each(["", "false", "1", "TRUE"])(
    "serves no metadata, challenge or redirect with flag=%s",
    async (flag) => {
      vi.stubEnv("MCP_PERSONAL_ENABLED", flag);
      try {
        const response = await GET(
          new Request(
            "https://cloud-palette.com/.well-known/oauth-protected-resource/api/mcp/personal",
          ),
        );
        expect(response.status).toBe(404);
        expect(await response.text()).toBe("");
        expect(response.headers.get("www-authenticate")).toBeNull();
        expect(response.headers.get("location")).toBeNull();
        expect(response.headers.get("cache-control")).toBe("private, no-store");
      } finally {
        vi.unstubAllEnvs();
      }
    },
  );
  it("builds the RFC 9728 resource contract with the canonical AS issuer", async () => {
    const response =
      createMcpDiscoveryContract(metadata()).resourceMetadataResponse();
    expect(await response.json()).toEqual({
      resource: MCP_PERSONAL_RESOURCE,
      authorization_servers: [MCP_AUTHORIZATION_ISSUER],
      scopes_supported: ["read:profiles"],
      bearer_methods_supported: ["header"],
    });
    const url = new URL(MCP_RESOURCE_METADATA_URL);
    expect(url.origin).toBe(new URL(MCP_PERSONAL_RESOURCE).origin);
    expect(url.pathname).toBe(
      `/.well-known/oauth-protected-resource${new URL(MCP_PERSONAL_RESOURCE).pathname}`,
    );
    expect(MCP_AS_METADATA_URL).toBe(
      `${MCP_AUTHORIZATION_ISSUER}/.well-known/openid-configuration`,
    );
    expect(response.headers.get("cache-control")).toBe("private, no-store");
  });
  it.each([undefined, "invalid_token", "insufficient_scope"] as const)(
    "keeps challenge and metadata aligned for %s",
    async (error) => {
      const response =
        createMcpDiscoveryContract(metadata()).unauthorizedResponse(error);
      expect(response.status).toBe(error === "insufficient_scope" ? 403 : 401);
      expect(response.headers.get("www-authenticate")).toBe(
        `Bearer resource_metadata="${MCP_RESOURCE_METADATA_URL}", scope="read:profiles"${error ? `, error="${error}"` : ""}`,
      );
      expect(response.headers.get("cache-control")).toBe("private, no-store");
      expect(await response.json()).toEqual({ error: error ?? "unauthorized" });
    },
  );
  it.each([
    { issuer: "https://attacker.invalid/oauth" },
    { token_endpoint: "https://attacker.invalid/token" },
    { authorization_endpoint: "https://attacker.invalid/auth" },
    { revocation_endpoint: undefined },
    { scopes_supported: ["openid"] },
    { code_challenge_methods_supported: ["plain", "S256"] },
    { response_types_supported: ["code", "token"] },
    { grant_types_supported: ["authorization_code"] },
    { registration_endpoint: "https://cloud-palette.com/oauth/reg" },
    { client_id_metadata_document_supported: true },
  ])("rejects deployment/policy mismatch %#", (patch) => {
    expect(() =>
      createMcpDiscoveryContract({ ...metadata(), ...patch }),
    ).toThrow("MCP_DISCOVERY_CONFIGURATION_MISMATCH");
  });
});

it.skipIf(Number(process.versions.node.split(".")[0]) < 22)(
  "matches discovery generated by the real AS handler (Node 22, loopback only)",
  async () => {
    const { createServer } = await import("node:http");
    const { generateKeyPairSync, randomBytes } = await import("node:crypto");
    const { Provider } = await import("oidc-provider");
    const { createMcpAuthorizationPolicy } =
      await import("@/lib/mcpAuthorizationConfig");
    const { privateKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });
    const provider = new Provider(MCP_AUTHORIZATION_ISSUER, {
      ...(await createMcpAuthorizationPolicy()),
      jwks: {
        keys: [
          {
            ...privateKey.export({ format: "jwk" }),
            kid: "temporary-test",
            use: "sig",
            alg: "RS256",
          },
        ],
      },
      cookies: { keys: [randomBytes(32).toString("hex")] },
    });
    // Emulate the trusted TLS proxy without making any external connection.
    provider.proxy = true;
    const callback = provider.callback();
    const server = createServer((request, response) => {
      // Node mount contract: preserve the original URL while stripping /oauth.
      Object.assign(request, { originalUrl: request.url });
      request.url = request.url?.slice("/oauth".length);
      return callback(request, response);
    });
    await new Promise<void>((resolve, reject) => {
      server.once("error", reject);
      server.listen(0, "127.0.0.1", resolve);
    });
    try {
      const address = server.address() as import("node:net").AddressInfo;
      const response = await fetch(
        `http://127.0.0.1:${address.port}/oauth/.well-known/openid-configuration`,
        {
          headers: {
            "x-forwarded-host": "cloud-palette.com",
            "x-forwarded-proto": "https",
          },
        },
      );
      expect(response.status).toBe(200);
      const actual = await response.json();
      expect(actual).toMatchObject({
        ...metadata(),
        scopes_supported: expect.arrayContaining(["read:profiles"]),
      });
      expect(() => createMcpDiscoveryContract(actual)).not.toThrow();
      expect(actual.introspection_endpoint).toBeUndefined();
      expect(actual.registration_endpoint).toBeUndefined();
    } finally {
      await new Promise<void>((resolve, reject) =>
        server.close((error) => (error ? reject(error) : resolve())),
      );
    }
  },
);
